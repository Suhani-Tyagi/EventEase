import datetime as dt
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field, field_validator


class EventType(StrEnum):
    """Allowed event types."""

    WEDDING = "wedding"
    BIRTHDAY = "birthday"
    COMMUNITY = "community"


class ChecklistStatus(StrEnum):
    """Vendor checklist task statuses."""

    TODO = "to-do"
    CONTACTED = "contacted"
    BOOKED = "booked"


class StrictBaseModel(BaseModel):
    """Base model that forbids unknown fields and enforces strict validation."""

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
        validate_assignment=True,
    )


class EventIntakeRequest(StrictBaseModel):
    """Event intake request model with strict validation boundaries."""

    event_type: EventType = Field(
        ...,
        description="Type of the celebration or event",
    )
    date: dt.date = Field(
        ...,
        description="Event date (must be in the future)",
    )
    guest_count: int = Field(
        ...,
        ge=1,
        le=10000,
        description="Expected number of attendees (1 to 10,000)",
    )
    total_budget: float = Field(
        ...,
        gt=0,
        le=50_000_000,
        description="Total allocated budget (> 0 and <= 50,000,000)",
    )
    currency: str = Field(
        default="USD",
        min_length=3,
        max_length=5,
        pattern=r"^[A-Z]{3,5}$",
        description="ISO currency code (e.g., USD, EUR, GBP, INR)",
    )
    city: str = Field(
        ...,
        min_length=2,
        max_length=100,
        description="Host city or region",
    )
    theme: str | None = Field(
        default=None,
        max_length=120,
        description="Preferred theme or stylistic aesthetic",
    )
    cultural_dietary_preferences: str | None = Field(
        default=None,
        max_length=200,
        description="Dietary requirements or cultural traditions",
    )
    special_notes: str | None = Field(
        default=None,
        max_length=500,
        description="Any specific requirements or considerations",
    )

    @field_validator("date")
    @classmethod
    def validate_future_date(cls, v: dt.date) -> dt.date:
        """Ensure the scheduled event date is strictly in the future."""
        today = dt.date.today()
        if v <= today:
            raise ValueError(
                f"Event date must be in the future (after {today.isoformat()})"
            )
        return v


class BudgetAllocationItem(StrictBaseModel):
    """Single category allocation within the budget."""

    category: str = Field(..., description="Expense category name")
    percentage: float = Field(..., description="Allocated percentage of total budget")
    amount: float = Field(..., description="Calculated monetary amount")
    description: str = Field(..., description="Short explanation of what is covered")


class BudgetPlan(StrictBaseModel):
    """Complete budget breakdown with warnings and per-guest metrics."""

    total_budget: float
    currency: str
    guest_count: int
    cost_per_guest: float
    realistic: bool
    warning: str | None = None
    items: list[BudgetAllocationItem]
    explanation: str


class TimelineMilestone(StrictBaseModel):
    """Milestone task group scheduled relative to the event date."""

    period_label: str
    target_date: dt.date
    days_before_event: int
    tasks: list[str]
    description: str


class TimelinePlan(StrictBaseModel):
    """Backward-planned timeline with adaptive compression flags."""

    event_date: dt.date
    days_remaining: int
    is_compressed: bool
    advisory: str | None = None
    milestones: list[TimelineMilestone]


class ChecklistTask(StrictBaseModel):
    """Vendor checklist task with actionable questions to ask."""

    id: str
    category: str
    vendor_type: str
    questions_to_ask: list[str]
    status: ChecklistStatus = ChecklistStatus.TODO
    notes: str | None = None


class VendorChecklist(StrictBaseModel):
    """Collection of checklist tasks specific to an event type."""

    event_type: EventType
    tasks: list[ChecklistTask]


class PersonalizedIdeas(StrictBaseModel):
    """Structured suggestions generated by GenAI or curated fallback."""

    themes: list[str] = Field(default_factory=list)
    decor: list[str] = Field(default_factory=list)
    menu: list[str] = Field(default_factory=list)
    activities: list[str] = Field(default_factory=list)
    budget_saving_tips: list[str] = Field(default_factory=list)
    is_fallback: bool = False
    fallback_reason: str | None = None


class ChecklistStatusUpdate(StrictBaseModel):
    """Request payload to update task status."""

    task_id: str
    status: ChecklistStatus


class FullEventPlan(StrictBaseModel):
    """Unified celebration plan incorporating all deliverables."""

    intake: EventIntakeRequest
    budget: BudgetPlan
    timeline: TimelinePlan
    checklist: VendorChecklist
    ideas: PersonalizedIdeas
    generated_at: dt.datetime
